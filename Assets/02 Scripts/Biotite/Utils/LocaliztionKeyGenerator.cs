#if UNITY_EDITOR
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.Localization;
using UnityEngine;

//유니티 localization 에 있는 키를 전부 가지고 와서 변수형태로 변환 합니다.
public class LocalizationKeyGenerator
{
    // 생성될 C# 파일의 저장 경로 및 클래스 설정
    private const string OutputFilePath = "Assets/02 Scripts/Biotite/Utils/LocaliztionKeyCode.cs";
    private const string ClassName = "LocaliztionKeyCode";
    
    
    
    /// <summary>
    /// 모든 테이블의 키값을 가지고와 키들을 상수로 만들어 저장합니다.
    /// </summary>
    [MenuItem("Tools/Localization/Generate Key Constants")]
    public static void GenerateKeys()
    {
        // 1. 유니티 Localization 에셋에서 모든 String Table Collection 가져오기
        var collections = LocalizationEditorSettings.GetStringTableCollections();

        if (collections == null || collections.Count == 0)
        {
            Debug.LogWarning("[LocKeyGen] String Table Collection을 찾을 수 없습니다.");
            return;
        }

        StringBuilder sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// LocalizationKeyGenerator 자동으로 생성되서 관리되는 클래스 입니다 수정하면 안됩니다.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine($"    public static class {ClassName}");
        sb.AppendLine("    {");
        
        foreach (var collection in collections)
        {
            sb.AppendLine($"        #region Table: {collection.TableCollectionName}");
            
            foreach (var entry in collection.SharedData.Entries)
            {
                string rawKey = entry.Key;
                if (string.IsNullOrEmpty(rawKey)) continue;
                
                string safeIdentifier = FormatToValidIdentifier(rawKey);

                sb.AppendLine($"        public const string {safeIdentifier} = \"{rawKey}\";");
            }

            sb.AppendLine("        #endregion");
            sb.AppendLine();
        }
        
        sb.AppendLine("}");
        
        string directory = Path.GetDirectoryName(OutputFilePath);
        if (!Directory.Exists(directory))
        {
            Directory.CreateDirectory(directory);
        }

        File.WriteAllText(OutputFilePath, sb.ToString(), Encoding.UTF8);
        AssetDatabase.Refresh();

        Debug.Log($"[LocKeyGen] 성공적으로 C# Key 클래스를 생성했습니다: {OutputFilePath}");
    }

    /// <summary>
    /// 원본 키 문자열을 C# 변수명 규칙에 맞게 변환합니다.
    /// </summary>
    private static string FormatToValidIdentifier(string rawKey)
    {
        string sanitized = Regex.Replace(rawKey, @"[^a-zA-Z0-9_]", "_");
        
        sanitized = sanitized.ToUpper();
        
        if (char.IsDigit(sanitized[0]))
        {
            sanitized = "_" + sanitized;
        }

        return sanitized;
    }
}
#endif